create policy "departments visible to authenticated users" on public.departments for select to authenticated using(true);
create policy "profile visibility within scope" on public.profiles for select to authenticated using(public.is_ceo() or department_id=public.current_department() or id=auth.uid());
create policy "profile self update limited" on public.profiles for update to authenticated using(id=auth.uid()) with check(id=auth.uid() and role=public.current_role() and department_id=public.current_department());
create policy "CEO manages profiles" on public.profiles for update to authenticated using(public.is_ceo()) with check(role in ('staff','admin','boss'));

create policy "issues visible within scope" on public.issues for select to authenticated using(public.is_ceo() or department_id=public.current_department() or created_by=auth.uid());
create policy "authorized users create issues" on public.issues for insert to authenticated with check(created_by=auth.uid() and (public.is_ceo() or department_id=public.current_department()));
create policy "department and CEO update issues" on public.issues for update to authenticated using(public.is_ceo() or department_id=public.current_department()) with check(public.is_ceo() or department_id=public.current_department());
create policy "issue history visible in scope" on public.issue_updates for select to authenticated using(exists(select 1 from public.issues i where i.id=issue_id));
create policy "issue history can be added in scope" on public.issue_updates for insert to authenticated with check(user_id=auth.uid() and exists(select 1 from public.issues i where i.id=issue_id and (public.is_ceo() or i.department_id=public.current_department())));

create policy "resolution submissions visible in scope" on public.resolution_submissions for select to authenticated using(exists(select 1 from public.issues i where i.id=issue_id and (public.is_ceo() or i.department_id=public.current_department())));
create policy "department submits resolution" on public.resolution_submissions for insert to authenticated with check(submitted_by=auth.uid() and exists(select 1 from public.issues i where i.id=issue_id and i.department_id=public.current_department()));
create policy "CEO reviews resolutions" on public.resolution_submissions for update to authenticated using(public.is_ceo()) with check(public.is_ceo());

create policy "finance visible in scope" on public.finance_entries for select to authenticated using(public.is_ceo() or department_id=public.current_department());
create policy "department submits finance" on public.finance_entries for insert to authenticated with check(submitted_by=auth.uid() and department_id=public.current_department());
create policy "CEO updates finance" on public.finance_entries for update to authenticated using(public.is_ceo()) with check(public.is_ceo());
create policy "reports visible in scope" on public.reports for select to authenticated using(public.is_ceo() or department_id=public.current_department());
create policy "department submits reports" on public.reports for insert to authenticated with check(submitted_by=auth.uid() and department_id=public.current_department());
create policy "CEO reviews reports" on public.reports for update to authenticated using(public.is_ceo()) with check(public.is_ceo());
create policy "announcements visible to authenticated" on public.announcements for select to authenticated using(true);
create policy "CEO creates announcements" on public.announcements for insert to authenticated with check(public.is_ceo() and created_by=auth.uid());
create policy "audit visible to CEO" on public.audit_logs for select to authenticated using(public.is_ceo());
create policy "authenticated actions append audit" on public.audit_logs for insert to authenticated with check(actor_id=auth.uid());

