-- AHB Issue Tracker v2 — production database foundation for Supabase.
-- Run in a NEW Supabase project. This SQL is not connected to the browser demo yet.
create extension if not exists pgcrypto;

create table if not exists public.departments (
  id smallint generated by default as identity primary key,
  name text not null unique
);
insert into public.departments(name) values
 ('Fund Services'),('IT Department'),('Finance'),('Accounts'),('Estates'),('Human Resources'),('Project Management')
on conflict(name) do nothing;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null,
  department_id smallint references public.departments(id),
  role text not null default 'staff' check(role in ('staff','admin','boss')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint boss_has_no_department check (role <> 'boss' or department_id is null)
);

create table if not exists public.issues (
  id bigint generated always as identity primary key,
  issue_number text unique not null default ('AHB-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,8))),
  title text not null,
  issue_type text not null default 'Operational issue',
  description text not null,
  priority text not null default 'Medium' check(priority in ('Low','Medium','High','Urgent')),
  department_id smallint not null references public.departments(id),
  created_by uuid references public.profiles(id) on delete set null,
  assigned_to uuid references public.profiles(id) on delete set null,
  deadline date,
  status text not null default 'open' check(status in ('open','in_progress','pending','awaiting_verification','resolved','rejected')),
  progress smallint not null default 0 check(progress between 0 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table if not exists public.issue_updates (
  id bigint generated always as identity primary key,
  issue_id bigint not null references public.issues(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  note text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.resolution_submissions (
  id bigint generated always as identity primary key,
  issue_id bigint not null references public.issues(id) on delete cascade,
  submitted_by uuid references public.profiles(id) on delete set null,
  resolution_description text not null,
  action_taken text not null,
  completed_on date not null,
  responsible_officer text not null,
  evidence_path text,
  review_status text not null default 'submitted' check(review_status in ('submitted','approved','rejected')),
  review_comment text,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.finance_entries (
  id bigint generated always as identity primary key,
  department_id smallint not null references public.departments(id),
  category text not null check(category in ('cash_in','cash_out','asset','liability')),
  description text not null,
  amount numeric(18,2) not null check(amount >= 0),
  entry_date date not null,
  source_reference text,
  submitted_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.reports (
  id bigint generated always as identity primary key,
  department_id smallint not null references public.departments(id),
  title text not null,
  report_type text not null check(report_type in ('Financial','Operational','Project progress','Assets','Other')),
  file_path text not null,
  file_name text not null,
  submitted_by uuid references public.profiles(id) on delete set null,
  status text not null default 'submitted' check(status in ('submitted','approved','rejected')),
  review_comment text,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.announcements (
  id bigint generated always as identity primary key,
  title text not null,
  body text not null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);
create table if not exists public.audit_logs (
  id bigint generated always as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.current_role() returns text
language sql stable security definer set search_path=public
as $$ select role from public.profiles where id=auth.uid() and is_active=true $$;
create or replace function public.current_department() returns smallint
language sql stable security definer set search_path=public
as $$ select department_id from public.profiles where id=auth.uid() and is_active=true $$;
create or replace function public.is_ceo() returns boolean
language sql stable security definer set search_path=public
as $$ select coalesce(public.current_role()='boss',false) $$;
create or replace function public.is_dept_admin() returns boolean
language sql stable security definer set search_path=public
as $$ select coalesce(public.current_role()='admin',false) $$;

create or replace function public.create_profile_for_auth_user() returns trigger
language plpgsql security definer set search_path=public
as $$ begin
 insert into public.profiles(id,email,full_name,department_id)
 values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name','New user'),nullif(new.raw_user_meta_data->>'department_id','')::smallint)
 on conflict(id) do nothing;
 return new;
end $$;
drop trigger if exists on_auth_user_created_ahb on auth.users;
create trigger on_auth_user_created_ahb after insert on auth.users for each row execute procedure public.create_profile_for_auth_user();

